// `npm run sync-wasm`: the built wasm quoter → this package.
//
//   rust/target/wasm-dist/floor_quote_bg.wasm, floor_quote.js, floor_quote.d.ts, floor_quote_bg.wasm.d.ts
//     → wasm/<same names>                (byte-for-byte copies; the hash is of the .wasm)
//     → wasm/SHA256SUMS, src/generated/wasm.ts  (WASM_SHA256, WASM_BYTES)
//
// The wasm is `rust/crates/floor-quote-wasm` compiled for `wasm32-unknown-unknown` and bound with
// `wasm-bindgen --target web` (wasm-bindgen-cli 0.2.128) by `scripts/build-wasm.sh` at the repository root
// (`npm run build-wasm` runs both steps). The copies in `wasm/` are COMMITTED, so an install needs no Rust;
// `npm run check-wasm` rebuilds from source and fails unless the result equals them byte for byte.
// ⛔ Fails, never warns, when the wasm or its glue is missing, or when the glue does not export
//    every function the wrapper calls (`QuoteFns`: `@carpenter/sdk`'s plus `src/quote/quoter.ts`'s four): a package that
//    ships without its quoter, or with a renamed export, is the one thing this step must stop.
// Env: FLOOR_WASM_DIR names the source directory (default: the repository's rust/target/wasm-dist).

import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { REQUIRED_EXPORTS, WEB_TARGET_MARKERS } from './wasm-exports.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const src = resolve(process.env.FLOOR_WASM_DIR ?? join(pkg, '../../rust/target/wasm-dist'));
const out = join(pkg, 'wasm');

function fail(msg) {
  console.error(`sync-wasm: ${msg}`);
  process.exit(1);
}

const wasmPath = join(src, 'floor_quote_bg.wasm');
const gluePath = join(src, 'floor_quote.js');
const dtsPath = join(src, 'floor_quote.d.ts');
for (const p of [wasmPath, gluePath, dtsPath]) {
  if (!existsSync(p)) fail(`missing ${p} — build the quoter wasm (bash scripts/build-wasm.sh at the repository root) or name its directory with FLOOR_WASM_DIR`);
}

const glue = readFileSync(gluePath, 'utf8');
const missing = REQUIRED_EXPORTS.filter((name) => !new RegExp(`export function ${name}\\(`).test(glue));
if (missing.length) fail(`${gluePath} does not export ${missing.join(', ')} (the wasm crate changed; update the QuoteFns wrappers)`);
const absent = WEB_TARGET_MARKERS.filter(([, re]) => !re.test(glue)).map(([what]) => what);
if (absent.length) {
  fail(`${gluePath} is not a wasm-bindgen --target web module (no ${absent.join(', no ')}) — scripts/build-wasm.sh passes --target web`);
}

const bytes = readFileSync(wasmPath);
const sha = createHash('sha256').update(bytes).digest('hex');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const name of ['floor_quote_bg.wasm', 'floor_quote.js', 'floor_quote.d.ts', 'floor_quote_bg.wasm.d.ts']) {
  const from = join(src, name);
  if (existsSync(from)) copyFileSync(from, join(out, name));
}
writeFileSync(join(out, 'SHA256SUMS'), `${sha}  floor_quote_bg.wasm\n`);

mkdirSync(join(pkg, 'src/generated'), { recursive: true });
writeFileSync(
  join(pkg, 'src/generated/wasm.ts'),
  '// GENERATED by scripts/sync-wasm.mjs. Do not edit.\n' +
    `/** sha256 of the shipped \`wasm/floor_quote_bg.wasm\` (\`npm run check-wasm\` rebuilds it from source). */\n` +
    `export const WASM_SHA256 = '${sha}';\n` +
    `/** Its size in bytes (kept under 400,000). */\n` +
    `export const WASM_BYTES = ${bytes.length};\n`,
);
console.log(`sync-wasm: floor_quote_bg.wasm ${bytes.length} B sha256 ${sha} → wasm/`);
